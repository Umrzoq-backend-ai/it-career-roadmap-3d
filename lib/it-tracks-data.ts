/**
 * Generates rich, beginner-friendly explanation & code example for any topic in any of the 15 IT tracks
 */
function buildTopicExplanation(
  track: ITTrack,
  mod: TrackModule,
  topicTitle: string,
  lessonNum: string
): { explanation: string; whyLearn: string; exampleCode: string } {
  const skillTag = mod.keySkills[0] || track.logoText;
  const explanation = `"${topicTitle}" — bu ${track.uzbekTitle} yo‘nalishining ${mod.index}-bosqichidagi (${mod.title}) asosiy amaliy mavzulardan biridir. Ushbu darsda siz ${skillTag} texnologiyasining ichki ishlash mantiqini noldan boshlab real misollar orqali o‘zlashtirasiz.`;
  const whyLearn = `${track.targetRole} sifatida ishga kirishda va "${track.projects[Number(mod.index) - 1]?.title || track.projects[0].title}" kabi real loyihalarni xatosiz qurishda aynan shu mavzu poydevor bo‘lib xizmat qiladi.`;
  const exampleCode = `# ${track.title} — Dars ${lessonNum}\n# Modul ${mod.index}: ${mod.shortTitle}\n# Mavzu: ${topicTitle}\n# Asosiy ko‘nikmalar: ${mod.keySkills.join(', ')}`;
  return { explanation, whyLearn, exampleCode };
}

/**
 * Converts ANY of the 15 IT Career Tracks into the 3D City Map's 7 Modules + 7 Projects structure
 * while preserving the exact 3D coordinates and collider IDs so the 3D city switches instantaneously!
 */
export function getCityDataForTrack(trackId: string): {
  track: ITTrack;
  modules: CourseModule[];
  projects: CourseProjectItem[];
  districts: string[];
} {
  const track =
    IT_CAREER_TRACKS.find((t) => t.id === trackId) ||
    IT_CAREER_TRACKS.find((t) => t.id === 'python-backend') ||
    IT_CAREER_TRACKS[0];

  // If Python Backend is selected, preserve all 108 original lessons & Telegram URLs while enriching with explanations
  if (track.id === 'python-backend') {
    const enrichedModules: CourseModule[] = COURSE_MODULES.map((baseMod, idx) => {
      const trackMod = track.modules[idx] || track.modules[0];
      return {
        ...baseMod,
        lessons: baseMod.lessons.map((l) => {
          const info = buildTopicExplanation(track, trackMod, l.title, l.number);
          return {
            ...l,
            explanation: info.explanation,
            whyLearn: info.whyLearn,
            exampleCode: info.exampleCode,
          };
        }),
      };
    });

    return {
      track,
      modules: enrichedModules,
      projects: COURSE_PROJECTS,
      districts: ['Python', 'SQL', 'Django', 'FastAPI'],
    };
  }

  // For all other 14 IT tracks, map their 7 modules & 7 projects onto the 3D City's 14 landmarks
  const mappedModules: CourseModule[] = COURSE_MODULES.map((baseMod, idx) => {
    const tMod = track.modules[idx] || track.modules[0];
    const palette = MODULE_COLORS[idx % MODULE_COLORS.length];
    const badgeTech = MODULE_TECH_BADGES[idx % MODULE_TECH_BADGES.length];
    const modNum = idx + 1;

    const lessons: LessonItem[] = tMod.topics.map((topicText, tIdx) => {
      const numberStr = `${modNum}.${tIdx + 1}`;
      const skillBadge = tMod.keySkills[tIdx % Math.max(1, tMod.keySkills.length)] || track.logoText;
      const info = buildTopicExplanation(track, tMod, topicText, numberStr);

      return {
        id: `${track.id}-m${modNum}-l${tIdx + 1}`,
        number: numberStr,
        title: topicText,
        tech: badgeTech,
        techLabel: skillBadge,
        tag: tIdx === tMod.topics.length - 1 ? 'project' : 'core',
        explanation: info.explanation,
        whyLearn: info.whyLearn,
        exampleCode: info.exampleCode,
      };
    });

    return {
      id: baseMod.id, // Keep canonical 3D building ID so 3D raycasting & labels bind seamlessly
      index: tMod.index,
      district: tMod.district || tMod.keySkills[0] || track.logoText,
      shortTitle: tMod.shortTitle,
      title: tMod.title,
      parkZone: `${track.title.toUpperCase()} · ZONA ${tMod.index}`,
      subtitle: tMod.subtitle,
      color: palette.color,
      hexColor: palette.hexColor,
      position: baseMod.position,
      buildingType: baseMod.buildingType,
      signTitle: tMod.shortTitle.toUpperCase(),
      signSubtitle: tMod.keySkills.slice(0, 3).join(' · ').toUpperCase(),
      outcome: `Ushbu modul yakunida siz ${tMod.keySkills.join(', ')} texnologiyalarini amalda qo‘llab, "${track.projects[idx]?.title || track.projects[0].title}" loyihasining asosiy qismini qura olasiz.`,
      lessons,
    };
  });

  const mappedProjects: CourseProjectItem[] = COURSE_PROJECTS.map((baseProj, idx) => {
    const tProj = track.projects[idx] || track.projects[0];
    return {
      id: baseProj.id, // Keep canonical 3D project building ID so 3D raycasting & labels bind seamlessly
      code: tProj.code,
      number: tProj.code,
      title: tProj.title,
      category: `${track.uzbekTitle.toUpperCase()} LOYIHASI`,
      company: tProj.companyTarget,
      subtitle: tProj.outcome,
      description: tProj.description,
      features: [
        `Arxitektura va texnologiyalar: ${tProj.techStack.join(', ')}`,
        `Amaliy natija: ${tProj.outcome}`,
        `${track.modules[idx]?.title || 'Modul'} bilimlari asosida noldan quriladi`,
        'GitHub portfolio, README hujjati va Production deploy bilan topshiriladi',
      ],
      techStack: baseProj.techStack,
      techLabels: tProj.techStack,
      brandText: tProj.brandText || track.logoText,
      brandBg: tProj.brandBg || track.logoBg,
      brandColor: tProj.brandColor || track.logoColor,
      position: baseProj.position,
      color: baseProj.color,
      hexColor: baseProj.hexColor,
      buildingType: baseProj.buildingType,
    };
  });

  const uniqueDistricts = Array.from(
    new Set(mappedModules.map((m) => m.district))
  ).slice(0, 4);

  return {
    track,
    modules: mappedModules,
    projects: mappedProjects,
    districts: uniqueDistricts,
  };
}
